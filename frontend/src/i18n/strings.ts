export function t(key: keyof typeof STRINGS, lang: Lang): string {
  const entry = STRINGS[key];
  if (!entry) return String(key);
  // For Luxembourgish, use the overlay first, then fall back to German.
  if (lang === "lb") {
    return LB_OVERRIDES[key as string] ?? entry.de ?? entry.en ?? String(key);
  }
  return entry[lang] ?? entry.en ?? String(key);
}
